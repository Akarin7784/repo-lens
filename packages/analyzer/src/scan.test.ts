import { mkdirSync, mkdtempSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { analyzeRepo } from './analyze.js';
import { scanRepo } from './scan.js';
import { isAssetSpec } from './typescript/lang.js';
import { parseWithTreeSitter } from './typescript/treesitter.js';

function repo(files: Record<string, string | Buffer>): string {
  const root = mkdtempSync(join(tmpdir(), 'rl-scan-'));
  for (const [p, c] of Object.entries(files)) {
    mkdirSync(dirname(join(root, p)), { recursive: true });
    writeFileSync(join(root, p), c);
  }
  return root;
}

describe('scanRepo 排除规则', () => {
  it('排除测试、文档、示例、基准、隐藏目录、生成/二进制/超大文件与符号链接', () => {
    const root = repo({
      'tsconfig.json': '{}',
      'src/a.ts': 'export const a = 1;',
      'src/a.test.ts': '',
      'src/b.spec.tsx': '',
      'src/__tests__/c.ts': '',
      'src/types.d.ts': '',
      'tests/x.ts': '',
      'docs/d.ts': '',
      'examples/e.ts': '',
      'bench/f.ts': '',
      '.claude/skills/g.ts': '',
      '.github/h.ts': '',
      'node_modules/p/index.js': '',
      'src/gen.ts': '// @generated by tool\nexport {}',
      'src/bin.ts': Buffer.from([0x61, 0x00, 0x62]),
      'src/big.ts': 'x'.repeat(600 * 1024),
      'src/vendor.min.js': '',
    });
    symlinkSync(join(root, 'src/a.ts'), join(root, 'src/link.ts'));
    symlinkSync('/etc', join(root, 'src/etc'));
    const r = scanRepo(root);
    expect(r.files).toEqual(['src/a.ts']);
    expect(r.skipped).toMatchObject({ symlinks: 2, tooLarge: 1, binary: 1, generated: 1 });
    expect(r.skipped.excludedFiles).toBe(3); // a.test.ts、b.spec.tsx、vendor.min.js
    expect(r.totalBytes).toBeGreaterThan(600 * 1024);
  });
});

describe('资源类 import', () => {
  it('isAssetSpec 识别 css/图片/字体,带 query 也算', () => {
    expect(isAssetSpec('./a.css')).toBe(true);
    expect(isAssetSpec('./logo.svg?url')).toBe(true);
    expect(isAssetSpec('pkg/dist/style.scss')).toBe(true);
    expect(isAssetSpec('./a')).toBe(false);
    expect(isAssetSpec('./a.js')).toBe(false);
    expect(isAssetSpec('react')).toBe(false);
  });

  it('只计数,不进图也不算 unresolved', async () => {
    const root = repo({
      'tsconfig.json': '{}',
      'src/a.ts': "import './a.css';\nimport logo from './logo.svg';\nimport { b } from './b';\n",
      'src/b.ts': 'export const b = 1;',
      'src/a.css': '',
    });
    const r = await analyzeRepo({ root, files: scanRepo(root).files });
    expect(r.stats.assetImports).toBe(2);
    expect(r.stats.unresolved).toBe(0);
    expect(r.graph.edges.map((e) => e.target)).toEqual(['f:src/b.ts']);
    expect(r.graph.nodes.find((n) => n.id === 'f:src/a.ts')).not.toHaveProperty('externalDeps');
  });
});

describe('单文件解析超时', () => {
  it('超时返回 timedOut 的空结果,节点仍保留', () => {
    const content = Array.from({ length: 20000 }, (_, i) => `export const a${i} = f(${i});`).join(
      '\n',
    );
    const r = parseWithTreeSitter({ path: 'big.ts', content }, { timeoutMs: 1 });
    expect(r.timedOut).toBe(true);
    expect(r.imports).toEqual([]);
    expect(r.loc).toBe(20000);
  });

  it('analyzeRepo 在并发下统计超时文件', async () => {
    const big = Array.from({ length: 20000 }, (_, i) => `export const a${i} = f(${i});`).join('\n');
    const root = repo({ 'tsconfig.json': '{}', 'src/big.ts': big, 'src/a.ts': 'export {}' });
    const seen: number[] = [];
    const r = await analyzeRepo(
      { root, files: ['src/a.ts', 'src/big.ts'] },
      { parseTimeoutMs: 1, concurrency: 2, onFileParsed: (d) => void seen.push(d) },
    );
    expect(r.stats.timedOutFiles).toEqual(['src/big.ts']);
    expect(r.graph.nodes.some((n) => n.id === 'f:src/big.ts')).toBe(true);
    expect(seen).toEqual([1, 2]);
  });
});
